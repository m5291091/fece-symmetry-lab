"""§8.6.3 の対称度表示変換（`100% - ずれ%`）の唯一の実装。

利用者が読む主表示は「どれだけずれているか」ではなく「どれだけ対称か」とする。

    symmetry_percent = clamp(100 × (1 - d), 0, 100)

- **表示専用の変換であり、指標そのものではない。** `d` 自体の定義は変えない。
  同じ測定値を別の向きで読ませているにすぎない。
- 変換は線形・可逆で、**自由パラメータを持たない**。`symmetry_percent = 100 -
  deviation_percent` であり、利用者はどちらの向きへも暗算で戻せる。
- `d > 1`（対応点のずれが両眼間隔を超える、検出破綻に相当する状態）では 0% で
  下げ止まる。この clamp は表示上の下限であり、`d` 自体は上限なく記録される。
- 100% は対応点距離がすべて 0 になった場合の数学上の上限であり、望ましさ、
  正常性、美的品質、人物の優劣を意味しない。実写で 100% になることは保証しない。

**撤回**（2026-09-03 の指示、§0 項目 34）。`s_3d`（部位等重み距離）を 0〜100 の
「点」へ写す表示スケール（旧 `display-scale/1.0.0`）と、その表示値「全体のスコア」
を機能ごと削除した。本 module に残るのは `symmetry_percent` だけである。`s_3d`
自体は残り（§8.6.5）、内部記録の `distance3d_parts_equal_raw` 列（§9.2）と
`age-gate/1.0.0` の特徴量 `s3d_distance`（§10.11）として使われ続ける。
"""

from __future__ import annotations

import math


def symmetry_percent(distance: float | None) -> float | None:
    """§8.6.3 の対称度変換（`100% - ずれ%`）を、文字列ではなく数値のまま返す。

    **この式の唯一の実装である。** 読み手は 3 つある——`ui.readings`（テキストと
    HUD の折れ線グラフ）、`domain.session_summary`（FR-021 の中央値と四分位）、
    そして FR-042 のレポート。式を 2 か所に書くと、画面上の別々の場所が同じ測定値
    から別の数を出す。`ui.readings.symmetry_percent` はここへ委譲するだけである。

    線形かつ可逆で、較正された係数を持たない。したがって同じ測定値の読む向きを
    変えるだけであり、採点ではない（§8.6.3）。

    ずれが両眼間隔そのものを超える退化ケースのために 0% で下限を設ける。欠測と
    非有限値は欠測のまま返す——`min`/`max` の clamp は NaN を黙って 0.0 へ落とす
    ため、clamp より前に弾く。
    """
    if distance is None or not math.isfinite(distance):
        return None
    return min(100.0, max(0.0, (1.0 - distance) * 100.0))
