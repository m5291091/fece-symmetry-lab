from __future__ import annotations

import streamlit as st

from face_symmetry_lab.adapters.inference.onnx_age_gate import load_age_gate_spec
from face_symmetry_lab.adapters.io.model_store import ModelStoreError
from face_symmetry_lab.ui.model_setup import (
    demographic_asset,
    landmark_asset,
    segmenter_asset,
)


def _render_model_versions() -> None:
    st.subheader("モデルとバージョン")
    try:
        landmark = landmark_asset()
        st.markdown(f"- **顔ランドマーク**: {landmark.version} · sha256 `{landmark.sha256[:16]}…`")
    except ModelStoreError:
        st.caption("顔ランドマークモデルのmanifestを読み込めません。")
    try:
        demographic = demographic_asset()
        st.markdown(
            f"- **参考年齢・参考性別**: {demographic.version} · sha256 `{demographic.sha256[:16]}…`"
        )
    except ModelStoreError:
        st.caption("年齢・性別モデルのmanifestを読み込めません。")
    try:
        segmenter = segmenter_asset()
        st.markdown(
            f"- **背景置換（表示専用）**: {segmenter.version} · sha256 `{segmenter.sha256[:16]}…`"
        )
    except ModelStoreError:
        st.caption("背景置換モデルのmanifestを読み込めません。")
    try:
        age_gate = load_age_gate_spec()
        st.markdown(
            f"- **参考年齢の表示ゲート**: {age_gate.gate_version} · "
            f"spec_revision {age_gate.spec_revision} · "
            f"ONNX sha256 `{age_gate.onnx_sha256[:16]}…`"
        )
    except ValueError:
        st.caption("年齢ゲートのspecを読み込めません。")
    st.caption(
        "版とsha256は結果のエクスポートにも記録されます。"
        "詳細は docs/model-cards/ を参照してください。"
    )


def render_about_page() -> None:
    st.title("使い方と対称度の算出方法")
    st.caption("LOCAL PROCESSING · NO IMAGE STORAGE · RESEARCH USE")
    st.write(
        "Face Symmetry Lab は、Web カメラまたは静止画から顔のランドマークを端末内で解析し、"
        "左右差をわかりやすく可視化する研究・セルフチェック用ツールです。"
        "画像は外部へ送信・保存されず、同一人物・同一環境内での左右差と肌表面参考値の相対的な傾向、"
        "およびモデル推定の参考年齢・参考性別を確認できます。"
    )
    st.info(
        "試験中の指標です。撮影条件で値が動くため、"
        "数値の絶対値ではなく同一条件での相対変化だけを参照してください。"
    )

    st.header("左右差の算出方法")

    st.subheader("幾何左右差（4部位+全体、主指標は3D）")
    st.markdown(
        "1. MediaPipe Face Landmarker が検出する 478 点のランドマークのうち、"
        "版管理された左右対応点 63 組（126 点）だけを輪郭・目・鼻・口の 4 部位で使用します。\n"
        "2. 両眼の目頭・目尻の中点を結ぶ線が水平になるよう回転補正し、"
        "両眼の中点間距離を 1.0 として拡大縮小を正規化します"
        "（虹彩中心は視線で動くため基準にしません）。\n"
        "3. **主指標は 3D の object symmetry 解析です。** 折る平面（中心線）を先に決めず、"
        "対応点を鏡映してペア名を入れ替えた配置を、元の配置へ並進と回転だけで重ね合わせます"
        "（大きさは合わせません）。重ね合わせが最適な折り方を自動で見つけるため、"
        "姿勢（向き・傾き）に依存しません。\n"
        "4. 重ねきれずに残った残差の RMS（二乗平均平方根）が距離です。"
        "126 点をまとめた残差から全体の値を、部位ごとに読んだ残差から部位別の値を得ます。"
        "部位別は全体の内訳ではなく、ズレの分布を見るための並列の診断値です。\n"
        "5. 部位ごとのペア数の違いを均すため、部位を 1 票ずつ数えた総合量も"
        "「全体のスコア」として表示します。全体の対称度（対応点を 1 票ずつ数える）とは"
        "重みだけが異なる別の値で、通常は一致しません。較正された採点ではなく、"
        "採点や評価を目的とした値ではありません。\n"
        "6. 画面には**対称度**として表示します。両眼の間隔を 100% としたときのずれを、"
        "100% から引いた値です（例: ずれ 2.15% → 対称度 97.85%）。"
        "係数のない引き算だけの表示変換で、指標そのもの・エクスポートの値・`metric_version` は"
        "変わりません。ずれが両眼間隔を超える検出破綻時のみ 0% で下げ止まります。\n"
        "7. 実写では表示値が数パーセントポイントの狭い範囲に集まりやすく、"
        "その中の違いだけで対称・非対称を判定することはできません。部位別の値も、"
        "同じ条件で撮り直すだけで動く幅があり、その幅より小さい変化は部位別の値だけでは"
        "左右差の変化として読み取れません（部位ごとの個人差は未検証です）。\n"
        "8. 中心線（正中点の Total Least Squares 直線）で折りたたむ従来の 2D 指標も並行して"
        "算出し、エクスポートに `distance_*_raw`（`metric_version_2d`）として診断目的で残します。"
        "この 2D 指標は、目の左右差が正規化基準（眼アンカー）へ吸収されて距離へ現れないことと、"
        "鼻周辺の非対称が中心線を引きずって総合値を下げうることが実測で確認されているため、"
        "画面には表示しません。以前の版にあった感度係数 `k` と部位の重み `w` は、"
        "固定評価セットで校正されていない恣意的な値だったためどちらの指標からも廃止しました。\n"
        "9. 数学上、対応点の距離がすべて 0 なら対称度 100% になりますが、これは望ましさや"
        "優劣を意味せず、実写で 100% になることも保証しません。"
    )

    st.subheader("左右対称にそろえた位置・画像")
    st.markdown(
        "- 対応する左右のペアについて、実測点とその鏡映点の**中点**を「左右対称にそろえた位置」"
        "として算出します。正中点は中心線への垂線の足になります。\n"
        "- 対応するペアが定義されていない点（478 点のうち大半）は動かしません。推測で対応を"
        "補うことはしません。\n"
        "- 実測点と対称化点の距離は、上の RMS 距離のちょうど半分です。新しい指標ではなく、"
        "同じ測定値を形として見せているだけです。\n"
        "- 任意で、対応点を対称化位置へ移動させ、その間の画素を Delaunay 三角形ごとに変形した"
        "**対称化画像**も生成できます（既定 OFF）。画像の四隅と辺の中点を固定するため、"
        "ランドマークが覆わない髪・耳・首・背景は外周を保ったまま緩やかに追従し、"
        "境界付近に不自然さが残ることがあります。\n"
        "- 変形量が両眼間隔の 25% を超える場合は、画像を生成せず理由を表示します"
        "（検出が破綻した状態で人物として成立しない画像を作らないためです）。\n"
        "- 生成されるのは幾何変形された加工画像です。無加工の写真ではなく、より正しい・望ましい"
        "顔でもありません。加工画像であることを明示せずに提示・共有しないでください。"
    )

    st.subheader("肌表面参考値（実験値）")
    st.markdown(
        "- 顔crop に対して、channel 平均をそろえる Gray-world ホワイトバランスと "
        "5〜95 percentile を用いた明度正規化を端末内で適用します"
        "（過補正を避ける範囲へ補正量をclamp）。\n"
        "- 補正後、版管理された左右の頬 landmark 周辺を抽出し、輝度・色差の分散から色調均一性を、"
        "局所勾配からテクスチャ均一性を算出します。\n"
        "- ソフトウェア補正はカメラ固有の露出・HDR・レンズ・ISP処理までは復元できないため、"
        "同一人物・同一端末・近い照明での相対比較の補助に限られます。"
        "肌質、疾患、清潔さ、健康、美的品質は表しません。幾何の左右差には混合しません。"
    )

    st.subheader("参考年齢・参考性別")
    st.markdown(
        "- Open Model Zoo 2023.0 FP16 `age-gender-recognition-retail-0013` を、"
        "検証済みの公式 XML/BIN から再現可能な開発時変換で生成した固定 ONNX として "
        "`opencv-contrib-python` の DNN 機能で端末内推論します。\n"
        "- 入力は検出した単一顔の landmark bbox から作る BGR 62×62 の crop で、"
        "顔埋め込みは生成・保持しません。\n"
        "- 出力は連続値の年齢と `[female, male]` の 2 クラス確率で、対象は 18〜75 歳です。"
        "公開ベンチマークでは年齢平均誤差 6.99 年、性別accuracy 95.80% ですが、"
        "内部validation datasetの値であり、実利用時の精度を保証しません。\n"
        "- 年齢は「モデル推定の参考年齢」、性別は「外見からのモデル推定の参考性別」であり、"
        "本人の自己認識・法的性別・実年齢を表しません。左右差・肌表面参考値とは分離して扱います。"
    )

    st.subheader("同年齢・同性別の参照平均（併記、FR-039）")
    st.markdown(
        "- 参考年齢・参考性別を表示しているとき、吹き出し・HUD の各数値"
        "（全体の対称度・全体のスコア・部位別 4 つ）の下に、**同じ参考年齢・同じ参考性別の"
        "平均**と、表示値との差を併記します。差は「表示値 − 平均」で、括弧内に符号付きで"
        "示します。\n"
        "- 平均の出どころは、アプリに同梱した UTKFace の事前集計データ"
        "（**非商用研究限定**、`(人種, 性別, 年齢)` ごとの件数・平均・二乗偏差和）です。"
        "顔画像も 1 枚ごとの測定値も同梱していません。参照統計ブラウザのページでは、"
        "同じデータを人種・性別・年齢で自由に絞り込んで閲覧できます。\n"
        "- 母集団は**参考年齢（1 歳刻み）と参考性別だけ**で決めます。**人種では絞り込みません** "
        "——本アプリは人種を推定せず、推定する仕組みも持ちません（データセット側の人種は"
        "配布時の注釈です）。\n"
        "- **参考年齢・参考性別を表示していないときは併記しません。** 推定できなかったとき、"
        "表示を切っているとき、参考年齢の表示ゲートが働いたときのいずれも、平均も母集団も"
        "表示しません。\n"
        "- 該当する母集団が 8 件未満のとき、参考年齢が 18〜75 歳の外のとき、参照データを"
        "読み込めないときも併記しません。いずれの場合も左右差の分析・表示・エクスポートは"
        "そのまま続きます。\n"
        "- **偏差値・順位・パーセンタイル・分位は算出も表示もしません。** 示すのは平均と"
        "符号付きの差だけです。差は引き算であって、母集団の中の順序へ置き換えたものでは"
        "ありません。\n"
        "- この平均は探索的な記述統計で、**基準値でも目標値でもありません**。群ごとの差は、"
        "撮影条件・注釈・データの構成比・ランドマーク検出の群ごとの挙動差を含みうるため、"
        "差の原因を特定できません。個人評価・人物間比較には使用できません。"
    )

    st.subheader("主な誤差要因")
    st.markdown(
        "- 顔の向き、照明、影、レンズ歪み、ランドマーク検出誤差\n"
        "- 化粧、髭、眼鏡、頭部被覆\n"
        "- カメラの自動露出・ホワイトバランス・圧縮処理\n"
        "- 年齢・性別推定は、肌色、年齢層、照明条件によって精度が変わり得ます"
    )

    st.subheader("精度向上のために必要なこと")
    st.markdown(
        "- 固定評価セットでの距離分布の把握（参考統計であり、係数の校正ではありません）\n"
        "- 実写での姿勢角符号の確認\n"
        "- 3D 正規化との比較評価\n"
        "- 照明・ぼけを検知するゲートの追加\n"
        "- 同一端末での再撮影評価"
    )

    st.header("使用しないでください")
    st.markdown(
        "- 医療、本人確認、採用、保険、教育、監視、人物比較・人物評価への利用\n"
        "- **年齢認証、未成年判定、入場制限への利用。** "
        "参考年齢を表示してよいかを決める内部ゲートがありますが、"
        "これは年齢を判定する仕組みではありません。"
        "乳幼児の顔の幾何を見分けるだけで、学童期以上の年齢や 76 歳以上は判定できません。\n"
        "- 本人以外、または明示的な権限・同意のない人物の画像の使用\n"
        "- 専用の同意・保護設計なしの未成年者への利用\n"
        "- 対称度の高低による感情的な祝福・警告、人物間比較、平均顔との比較、ランキング\n"
        "- **参照平均との差を、順位・優劣・目標として扱うこと。** "
        "差は 2 つの数の引き算であり、母集団の中の位置づけでも達成度でもありません。"
    )

    st.header("プライバシーとデータの扱い")
    st.markdown(
        "- 画像・映像・ランドマーク・年齢帯・左右差の数値は外部へ送信せず、暗黙に保存もしません。\n"
        "- カメラは `127.0.0.1` のみで待ち受け、STUN/TURN や利用統計は既定で無効です。\n"
        "- 画像アップロードやカメラ利用は、事前の同意画面を完了するまで開始しません。\n"
        "- モデルは自動取得・自動更新せず、版と SHA-256 を追跡してエクスポート結果に記録します。\n"
        "- **結果レポート（HTML）を保存すると、顔写真を含む図がファイルへ入ります。**"
        "アプリが自動でファイルを作ることはなく、保存はダウンロード操作のときだけです。"
        "図を入れるかどうかは保存の直前で切り替えられます。"
        "保存した後のファイルはアプリの管理外で、共有先や複製をアプリからは制御できません。"
    )

    st.divider()
    _render_model_versions()
